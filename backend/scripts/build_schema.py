"""Turn the Drizzle migrations into a Supabase-free Postgres schema.

The business rules stay in the original SECURITY DEFINER functions. Supabase
Auth is replaced by public.users, and auth.uid() by public.current_user_id(),
which reads the transaction-local setting the API sets for each request.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / "drizzle" / "migrations"
OUT = ROOT / "backend" / "sql" / "01_schema.sql"

# 0003 is superseded by 0006 and creates triggers on auth.users.
INCLUDE = [
    "0000_migration.sql",
    "0001_migration.sql",
    "0002_expenses_module.sql",
    "0004_biory_master_data.sql",
    "0005_staff_requisitions.sql",
]

HEADER = """\
-- BIORY distribution schema for a standalone Postgres database.
-- Generated by backend/scripts/build_schema.py — regenerate instead of editing.
-- The API connects as biory_app. Tables are owned by the migration role, so
-- row level security applies to the API. SECURITY DEFINER functions keep the
-- ledger rules atomic and run as the owner.

create or replace function public.current_user_id() returns uuid
language sql stable
set search_path = public
as $$
  select nullif(current_setting('app.user_id', true), '')::uuid
$$;

"""

USERS = """\
create table public.users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  password_hash text not null,
  full_name text not null default '',
  email_confirmed_at timestamptz,
  created_at timestamptz not null default now()
);

"""

FOOTER = """
revoke execute on all functions in schema public from public;
grant usage on schema public to biory_app;
grant select, insert, update, delete on all tables in schema public to biory_app;
grant usage, select on all sequences in schema public to biory_app;
grant execute on all functions in schema public to biory_app;

-- Helpers that must only run inside other functions, not as API calls.
revoke execute on function public.next_doc_no(text) from biory_app;
revoke execute on function public._allocate_fefo(uuid, uuid, int) from biory_app;
revoke execute on function public._notify_user(uuid, text, text, text) from biory_app;
revoke execute on function public._notify_roles(public.app_role[], text, text, text) from biory_app;
revoke execute on function public._audit(text, text, text, jsonb, text) from biory_app;
revoke execute on function public._refresh_order_status(uuid) from biory_app;
revoke execute on function public._so_reserved(uuid, uuid) from biory_app;
revoke execute on function public._usable_qty(uuid, uuid) from biory_app;
"""


def strip_privileges(sql: str) -> str:
    kept: list[str] = []
    for line in sql.splitlines(keepends=True):
        stripped = line.lstrip().lower()
        if stripped.startswith("grant ") or stripped.startswith("revoke "):
            continue
        kept.append(line)
    return "".join(kept)


def transform(sql: str) -> str:
    sql = re.sub(
        r'create policy\s+"[^"]*"\s+on storage\..*?;\s*',
        "",
        sql,
        flags=re.IGNORECASE | re.DOTALL,
    )
    sql = strip_privileges(sql)
    sql = sql.replace("auth.uid()", "public.current_user_id()")
    sql = sql.replace("auth.users", "public.users")
    sql = sql.replace(" to authenticated", "")
    sql = sql.replace(" to anon", "")
    sql = re.sub(
        r"coalesce\(new\.raw_user_meta_data->>'full_name', new\.raw_user_meta_data->>'name', split_part\(new\.email, '@', 1\)\)",
        "coalesce(nullif(trim(new.full_name), ''), split_part(new.email, '@', 1))",
        sql,
    )
    marker = "create table public.profiles ("
    if marker not in sql:
        raise SystemExit("profiles table not found in migrations")
    sql = sql.replace(marker, USERS + marker, 1)
    return HEADER + sql.strip() + "\n" + FOOTER


def main() -> None:
    parts = []
    for name in INCLUDE:
        parts.append((MIGRATIONS / name).read_text(encoding="utf-8"))
    out = transform("\n\n".join(parts))
    if "auth.users" in out or "auth.uid()" in out or "storage." in out:
        raise SystemExit("schema still references Supabase auth or storage")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(out.splitlines())} lines)")


if __name__ == "__main__":
    main()
