-- Bangladesh divisions, districts and upazilas. Staff can add more from the chemist form.
create table if not exists public.geo_places (
  id uuid primary key default gen_random_uuid(),
  level text not null check (level in ('division', 'district', 'upazila')),
  name text not null,
  parent_id uuid references public.geo_places(id),
  created_at timestamptz not null default now(),
  check ((level = 'division') = (parent_id is null))
);
create unique index if not exists geo_places_root on public.geo_places (level, lower(name)) where parent_id is null;
create unique index if not exists geo_places_child on public.geo_places (level, parent_id, lower(name)) where parent_id is not null;
create index if not exists geo_places_parent on public.geo_places (parent_id);
alter table public.geo_places enable row level security;
drop policy if exists "geo places read" on public.geo_places;
create policy "geo places read" on public.geo_places for select using (true);
drop policy if exists "geo places insert" on public.geo_places;
create policy "geo places insert" on public.geo_places for insert
  with check (
    public.has_role(public.current_user_id(), 'sales_officer')
    or public.is_admin(public.current_user_id())
  );
grant select, insert on table public.geo_places to biory_app;

